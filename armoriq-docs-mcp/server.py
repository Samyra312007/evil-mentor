@mcp.tool()
def get_armoriq_architecture() -> str:
    """Get the ArmorIQ platform architecture overview.

    Returns a description of how the ArmorIQ components fit together:
    SDK, Proxy, CSRG-IAP, Backend, and MCP servers.
    """
    return """\
# ArmorIQ Architecture

## Components

### SDK (Python / TypeScript)
- Client initialization with API key
- Per-user scoping via for_user(email)
- Plan capture, token minting, and verified invocation
- Framework adapters (Google ADK live; CrewAI, LangChain, OpenAI, Anthropic planned)

### ArmorIQ Proxy
- Receives invoke() calls from the SDK
- Validates API key (bcrypt)
- Forwards to CSRG-IAP for cryptographic verification
- Routes verified requests to the target MCP server
- Endpoint: https://proxy.armoriq.ai

### CSRG-IAP (Intent Access Proxy)
- Converts plans to Merkle tree structures
- Computes SHA-256 plan hashes
- Signs tokens with Ed25519
- Verifies step proofs on each invoke()
- Issues delegation tokens for sub-agents
- Endpoint: https://iap.armoriq.ai

### Backend Services
- Policy management and enforcement
- Audit logs and compliance tracking
- Organization and user management
- MCP Registry
- Endpoint: https://api.armoriq.ai

### MCP Servers (yours)
- Registered on platform.armoriq.ai → MCP Registry
- Each has a unique ID and HTTPS endpoint
- Auth: none, bearer token, or API key
- Actions are the tools your agent can call

## Request Flow
1. SDK: capture_plan() → validates plan structure
2. SDK: get_intent_token() → Proxy → CSRG-IAP mints token (plan_hash, merkle_root, step_proofs)
3. SDK: invoke() → Proxy verifies Merkle proof + Ed25519 signature → routes to MCP
4. MCP executes action → result returned through Proxy → SDK

## Security Headers (invoke)
- X-API-Key: authentication
- X-CSRG-Path: path in plan (e.g., /steps/[0]/action)
- X-CSRG-Value-Digest: SHA256 hash of action value
- X-CSRG-Proof: JSON Merkle proof array

## Delegation Flow
1. Parent agent gets intent token
2. Parent calls delegate() with delegate's Ed25519 public key
3. CSRG-IAP creates restricted, time-limited delegation token
4. Sub-agent uses delegated token for authorized actions only

Full docs: https://docs.armoriq.ai
"""


