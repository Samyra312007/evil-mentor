@mcp.tool()
def search_armoriq_docs(query: str) -> str:
    """Search the ArmorIQ documentation index.

    Finds relevant documentation pages by matching your query against
    page titles, summaries, and tags. Returns the top matches with
    titles, URLs, and summaries.

    Args:
        query: Natural-language search query (e.g. "how to install",
               "invoke method", "error codes", "OpenClaw setup").
    """
    query_lower = query.lower()
    tokens = set(re.findall(r"[a-z0-9_]+", query_lower))

    scored: list[tuple[float, str, dict]] = []
    for key, page in DOC_PAGES.items():
        score = 0.0
        haystack = f"{page['title']} {page['summary']} {' '.join(page['tags'])} {key}".lower()

        # exact substring match in haystack
        if query_lower in haystack:
            score += 10

        # token overlap
        for tok in tokens:
            if tok in haystack:
                score += 2
            # bonus for tag match
            if tok in [t.lower() for t in page["tags"]]:
                score += 3

        if score > 0:
            scored.append((score, key, page))

    scored.sort(key=lambda x: -x[0])
    top = scored[:8]

    if not top:
        return (
            "No matching documentation pages found. "
            "Try broader terms like 'sdk', 'cli', 'install', 'invoke', 'openclaw', 'errors'."
        )

    lines = [f"Found {len(top)} result(s) for \"{query}\":\n"]
    for _score, key, page in top:
        lines.append(f"### {page['title']}")
        lines.append(f"URL: {page['url']}")
        lines.append(f"{page['summary']}")
        lines.append(f"Tags: {', '.join(page['tags'])}")
        lines.append("")

    return "\n".join(lines)


@mcp.tool()
def get_armoriq_doc_page(page_id: str) -> str:
    """Fetch the full content of a specific ArmorIQ documentation page.

    Use search_armoriq_docs first to find the right page_id, then call
    this to get the complete page content fetched live from docs.armoriq.ai.

    Args:
        page_id: The page identifier. Valid values:
            overview, installation, client-initialization, cli,
            configuration, core-methods, capture-plan, get-intent-token,
            invoke, delegate, integrations, data-models, mcp-directory,
            error-handling, advanced-usage, troubleshooting, best-practices,
            openclaw-getting-started
    """
    page = DOC_PAGES.get(page_id)
    if not page:
        available = ", ".join(sorted(DOC_PAGES.keys()))
        return f"Unknown page_id '{page_id}'. Available pages: {available}"

    try:
        content = _fetch(page["url"])
    except Exception as exc:
        return f"Failed to fetch {page['url']}: {exc}"

    header = f"# {page['title']}\nSource: {page['url']}\n\n"
    return header + content


@mcp.tool()
def list_armoriq_doc_pages() -> str:
    """List all available ArmorIQ documentation pages.

    Returns every page in the index with its ID, title, and one-line summary.
    Use the page ID with get_armoriq_doc_page() to fetch full content.
    """
    lines = ["# ArmorIQ Documentation Index\n"]
    for key, page in DOC_PAGES.items():
        lines.append(f"- **{key}** — {page['title']}")
        lines.append(f"  {page['summary']}")
    return "\n".join(lines)


